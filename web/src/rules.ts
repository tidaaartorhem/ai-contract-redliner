/**
 * rules.ts — TypeScript mirror of the RedlineDesk Python engine
 * (src/redlinedesk/assess.py + graph.py routing).
 *
 * Every rule reads expert-labeled CUAD clause spans and applies disclosed,
 * threshold-based tests — no LLM calls. Number words are normalized to
 * digits first ("twelve-month" -> "12-month", "sixty (60) days" -> "60 days"),
 * so the same parser works on written-out and numeric periods.
 *
 * Score: base + adjustment, capped at 100. Tier from score:
 *   score >= reject_bar (85) -> REJECT
 *   score >= flag_bar   (40) -> FLAG
 *   otherwise               -> ACCEPT
 * data/test-vectors.json (generated by the Python pipeline) keeps both
 * implementations in exact agreement.
 */

