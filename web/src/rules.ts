/** Mirror of Python assess.normalize_numbers. */
export function normalizeNumbers(text: string): string {
  let t = text.toLowerCase();
  for (const [word, digit] of NUMBER_WORDS) {
    t = t.replace(new RegExp(`\\b${word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "g"), digit);
  }
  t = t.replace(/\(\d+\)/g, "");
  return t.replace(/\s+/g, " ");
}

function firstInt(pattern: RegExp, text: string): number | null {
  const m = pattern.exec(text);
  return m ? parseInt(m[1], 10) : null;
}

/** Mirror of Python assess.parse_months. */
export function parseMonths(text: string): number | null {
  const n = firstInt(/(\d+)[\s-]*(?:months?|mos?)\b/, text);
  if (n !== null) return n;
  const y = firstInt(/(\d+)[\s-]*(?:years?|yrs?)\b/, text);
  return y !== null ? y * 12 : null;
}

/** Mirror of Python assess.parse_days. */
export function parseDays(text: string): number | null {
  const n = firstInt(/(\d+)[\s-]*(?:business\s+days?|days?)\b/, text);
  if (n !== null) return n;
  const m = firstInt(/(\d+)[\s-]*(?:months?|mos?)\b/, text);
  if (m !== null) return m * 30;
  const y = firstInt(/(\d+)[\s-]*(?:years?|yrs?)\b/, text);
  return y !== null ? y * 365 : null;
}

export function parseMoney(text: string): string | null {
  const m = /\$[\d,]+(?:\.\d+)?/.exec(text);
  return m ? m[0] : null;
}

export interface Thresholds {
  reject_bar: number;
  flag_bar: number;
}

export const DEFAULT_THRESHOLDS: Thresholds = { reject_bar: 85, flag_bar: 40 };

export type Tier = "ACCEPT" | "FLAG" | "REJECT";

export interface Assessment {
  rule_id: string;
  score: number;
  score_parts: { base: number; adjustment: number };
  evidence: string[];
  tier: Tier;
  present: boolean;
}

export interface RuleLite {
  id: string;
  title: string;
  stance: string;
  redline: string;
  fallback: string;
}

function result(
  ruleId: string,
  base: number,
  adjustment: number,
  evidence: string[],
  thresholds: Thresholds,
  present: boolean,
): Assessment {
  const score = Math.min(100, base + adjustment);
  const tier: Tier =
    score >= thresholds.reject_bar ? "REJECT" : score >= thresholds.flag_bar ? "FLAG" : "ACCEPT";
  return { rule_id: ruleId, score, score_parts: { base, adjustment }, evidence, tier, present };
}

function assessLiabilityCap(spans: string[], thresholds: Thresholds): Assessment {
  const text = spans.join(" ");
  const norm = normalizeNumbers(text);
  let months: number | null = null;
  if (/\b(fee|fees|paid|payable|consideration)\b/.test(norm)) months = parseMonths(norm);
  if (months !== null) {
    if (months >= 12) {
      return result("LIABILITY_CAP", 10, 0, [`cap of ${months} months' fees (playbook minimum: 12)`], thresholds, true);
    }
    return result("LIABILITY_CAP", 55, Math.min(29, (12 - months) * 3), [`cap of only ${months} months' fees (playbook minimum: 12)`], thresholds, true);
  }
  const money = parseMoney(text);
  if (money) {
    return result("LIABILITY_CAP", 60, 0, [`fixed-amount cap (${money}) — cannot verify against 12 months' fees`], thresholds, true);
  }
  return result("LIABILITY_CAP", 65, 0, ["cap language present but no amount or period stated"], thresholds, true);
}

function assessUncappedLiability(spans: string[], thresholds: Thresholds): Assessment {
  const low = spans.join(" ").toLowerCase();
  if (/\b(limited to|shall not exceed|maximum aggregate|capped at|cap of)\b/.test(low)) {
    return result("UNCAPPED_LIABILITY", 55, 0, ["carve-out from a stated cap (confidentiality / IP / indemnity)"], thresholds, true);
  }
  if (low.includes("in no event") && /\b(consequential|incidental|indirect|special|punitive)\b/.test(low)) {
    return result("UNCAPPED_LIABILITY", 45, 0, ["consequential-damages exclusion, not a general cap"], thresholds, true);
  }
  if (/\b(unlimited|uncapped|not be limited|without limit)\b/.test(low)) {
    return result("UNCAPPED_LIABILITY", 90, 0, ["liability stated as unlimited / uncapped"], thresholds, true);
  }
  return result("UNCAPPED_LIABILITY", 60, 0, ["uncapped-liability language, scope unclear"], thresholds, true);
}

function assessTermination(spans: string[], thresholds: Thresholds): Assessment {
  const days = parseDays(normalizeNumbers(spans.join(" ")));
  if (days !== null) {
    if (days >= 30) {
      return result("TERMINATION_CONVENIENCE", 10, 0, [`${days} days' notice (playbook minimum: 30)`], thresholds, true);
    }
    return result("TERMINATION_CONVENIENCE", 55, Math.min(29, 30 - days), [`only ${days} days' notice (playbook minimum: 30)`], thresholds, true);
  }
  return result("TERMINATION_CONVENIENCE", 60, 0, ["termination-for-convenience clause states no notice period"], thresholds, true);
}

function assessGoverningLaw(spans: string[], thresholds: Thresholds): Assessment {
  const low = spans.join(" ").toLowerCase();
  if (low.includes("ontario")) {
    return result("GOVERNING_LAW", 10, 0, ["governing law is Ontario, as the playbook requires"], thresholds, true);
  }
  for (const prov of [...CANADA_PROVINCES].sort()) {
    if (low.includes(prov)) {
      return result("GOVERNING_LAW", 55, 0, [`governing law is ${prov.replace(/\b\w/g, (c) => c.toUpperCase())} (Canada, but not Ontario)`], thresholds, true);
    }
  }
  if (low.includes("canada")) {
    return result("GOVERNING_LAW", 55, 0, ["governing law is Canada (not Ontario specifically)"], thresholds, true);
  }
  for (const st of [...US_STATES].sort()) {
    if (low.includes(st)) {
      return result("GOVERNING_LAW", 80, 0, [`governing law is ${st.replace(/\b\w/g, (c) => c.toUpperCase())} (US state, not Ontario)`], thresholds, true);
    }
  }
  if (/\blaws of the state\b/.test(low) || low.includes("state of")) {
    return result("GOVERNING_LAW", 80, 0, ["governing law is a US state (not Ontario)"], thresholds, true);
  }
  for (const j of [...OTHER_JURISDICTIONS].sort()) {
    if (low.includes(j)) {
      return result("GOVERNING_LAW", 80, 0, [`governing law is ${j.replace(/\b\w/g, (c) => c.toUpperCase())} (not Ontario)`], thresholds, true);
    }
  }
  return result("GOVERNING_LAW", 60, 0, ["governing-law clause found but jurisdiction not identified"], thresholds, true);
}

function assessIpAssignment(spans: string[], thresholds: Thresholds): Assessment {
  const low = spans.join(" ").toLowerCase();
  if (/\b(assign|become .* property|owned exclusively|hereby assigns)\b/.test(low)) {
    return result("IP_ASSIGNMENT", 65, 0, ["IP created under the agreement is assigned to the counterparty"], thresholds, true);
  }
  return result("IP_ASSIGNMENT", 45, 0, ["broad licence-back to the counterparty, not a full assignment"], thresholds, true);
}

function assessNonCompete(_spans: string[], hasException: boolean, thresholds: Thresholds): Assessment {
  if (hasException) {
    return result("NON_COMPETE", 15, 0, ["non-compete present but the contract carries stated carve-outs/exceptions"], thresholds, true);
  }
  return result("NON_COMPETE", 70, 0, ["non-compete with no stated carve-out or exception"], thresholds, true);
}

function assessNoSolicitEmployees(_spans: string[], thresholds: Thresholds): Assessment {
  return result("NO_SOLICIT_EMPLOYEES", 60, 0, ["employee non-solicit present (playbook: delete or cap at 12 months)"], thresholds, true);
}

function assessMfn(_spans: string[], thresholds: Thresholds): Assessment {
  return result("MFN", 90, 0, ["most-favoured-nation clause present (playbook: delete in full)"], thresholds, true);
}

function assessChangeOfControl(spans: string[], thresholds: Thresholds): Assessment {
  const low = spans.join(" ").toLowerCase();
  if (low.includes("terminat")) {
    return result("CHANGE_OF_CONTROL", 70, 0, ["counterparty may terminate on a change of control"], thresholds, true);
  }
  return result("CHANGE_OF_CONTROL", 60, 0, ["change-of-control clause gives the counterparty consent or notice rights"], thresholds, true);
}

function assessAutoRenewal(termSpans: string[], noticeSpans: string[], thresholds: Thresholds): Assessment {
  if (termSpans.length === 0 && noticeSpans.length === 0) {
    return result("AUTO_RENEWAL", 5, 0, ["no auto-renewal term found in the contract"], thresholds, true);
  }
  const term = termSpans.length > 0 ? parseMonths(normalizeNumbers(termSpans.join(" "))) : null;
  const notice = noticeSpans.length > 0 ? parseDays(normalizeNumbers(noticeSpans.join(" "))) : null;
  if (term !== null && term > 12) {
    return result("AUTO_RENEWAL", 55, Math.min(29, (term - 12) * 2), [`auto-renewal term of ${term} months (playbook maximum: 12)`], thresholds, true);
  }
  if (notice !== null && notice > 60) {
    return result("AUTO_RENEWAL", 55, Math.min(29, Math.floor((notice - 60) / 5)), [`opt-out notice of ${notice} days (playbook maximum: 60)`], thresholds, true);
  }
  if (term === null && notice === null) {
    return result("AUTO_RENEWAL", 60, 0, ["auto-renewal present but term and notice period not stated"], thresholds, true);
  }
  const bits: string[] = [];
  if (term !== null) bits.push(`renewal term ${term} months`);
  if (notice !== null) bits.push(`opt-out notice ${notice} days`);
  return result("AUTO_RENEWAL", 10, 0, [bits.join("; ") + " (within playbook limits)"], thresholds, true);
}

function assessAntiAssignment(spans: string[], thresholds: Thresholds): Assessment {
  const low = spans.join(" ").toLowerCase();
  // "Freely assignable" or "may assign ... without consent" is a pass.
  // NOTE: "shall not assign without consent" is consent-REQUIRED — the
  // word "without" alone must never trigger the free-assignment branch.
  const free =
    low.includes("freely assign") ||
    /may assign[^.]{0,120}without (the )?(prior )?(written )?consent/.test(low);
  if (free) {
    return result("ANTI_ASSIGNMENT", 15, 0, ["assignment permitted without counterparty consent"], thresholds, true);
  }
  if (low.includes("consent")) {
    return result("ANTI_ASSIGNMENT", 60, 0, ["assignment requires the counterparty's consent"], thresholds, true);
  }
  return result("ANTI_ASSIGNMENT", 55, 0, ["anti-assignment clause present; consent position unclear"], thresholds, true);
}

/**
 * Mirror of Python assess.assess_clause. For AUTO_RENEWAL, `spans` are the
 * Renewal Term spans and `noticeSpans` the Notice Period spans.
 */
export function assessClause(
  ruleId: string,
  spans: string[],
  thresholds: Thresholds = DEFAULT_THRESHOLDS,
  hasException = false,
  noticeSpans: string[] = [],
): Assessment {
  if (ruleId === "AUDIT_RIGHTS") {
    if (spans.length > 0) {
      return result("AUDIT_RIGHTS", 10, 0, ["audit rights present"], thresholds, true);
    }
    return result("AUDIT_RIGHTS", 55, 0, ["no audit-rights clause found (playbook requires one)"], thresholds, false);
  }
  if (ruleId === "AUTO_RENEWAL") {
    if (spans.length === 0 && noticeSpans.length === 0) {
      const r = result("AUTO_RENEWAL", 0, 0, ["clause category not present in this contract"], thresholds, false);
      r.tier = "ACCEPT";
      return r;
    }
    return assessAutoRenewal(spans, noticeSpans, thresholds);
  }
  if (spans.length === 0) {
    const r = result(ruleId, 0, 0, ["clause category not present in this contract"], thresholds, false);
    r.tier = "ACCEPT";
    return r;
  }
  switch (ruleId) {
    case "LIABILITY_CAP": return assessLiabilityCap(spans, thresholds);
    case "UNCAPPED_LIABILITY": return assessUncappedLiability(spans, thresholds);
    case "TERMINATION_CONVENIENCE": return assessTermination(spans, thresholds);
    case "GOVERNING_LAW": return assessGoverningLaw(spans, thresholds);
    case "IP_ASSIGNMENT": return assessIpAssignment(spans, thresholds);
    case "NON_COMPETE": return assessNonCompete(spans, hasException, thresholds);
    case "NO_SOLICIT_EMPLOYEES": return assessNoSolicitEmployees(spans, thresholds);
    case "MFN": return assessMfn(spans, thresholds);
    case "CHANGE_OF_CONTROL": return assessChangeOfControl(spans, thresholds);
    case "ANTI_ASSIGNMENT": return assessAntiAssignment(spans, thresholds);
    default: throw new Error(`unknown rule ${ruleId}`);
  }
}

/** Single-clause route: the same route logic as graph.py, for one clause. */
export type Route = "APPROVE" | "SEND_TO_LEGAL" | "ESCALATE";

export function routeForClause(assessment: Assessment): Route {
  if (assessment.tier === "REJECT") return "ESCALATE";
  if (assessment.tier === "FLAG") return "SEND_TO_LEGAL";
  return "APPROVE";
}
